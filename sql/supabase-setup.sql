-- GIMISCO media gallery + administrator access setup
-- Run in Supabase SQL Editor. This does not grant anyone admin access automatically.

create table if not exists public.media (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  url text not null,
  type text not null check (type in ('image','video')),
  storage_path text,
  created_at timestamptz not null default now()
);
alter table public.media enable row level security;
grant select on public.media to anon, authenticated;
grant insert, update, delete on public.media to authenticated;

-- Administrator authorization table:
create table if not exists public.gimisco_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.gimisco_admins enable row level security;
grant select on public.gimisco_admins to authenticated;

-- Create policies only if missing, so rerunning this file does not drop existing policies.
do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='media' and policyname='GIMISCO media public read') then
    create policy "GIMISCO media public read" on public.media for select to anon, authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='media' and policyname='GIMISCO admins insert media') then
    create policy "GIMISCO admins insert media" on public.media for insert to authenticated with check (exists (select 1 from public.gimisco_admins a where a.user_id = (select auth.uid())));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='media' and policyname='GIMISCO admins update media') then
    create policy "GIMISCO admins update media" on public.media for update to authenticated using (exists (select 1 from public.gimisco_admins a where a.user_id = (select auth.uid()))) with check (exists (select 1 from public.gimisco_admins a where a.user_id = (select auth.uid())));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='media' and policyname='GIMISCO admins delete media') then
    create policy "GIMISCO admins delete media" on public.media for delete to authenticated using (exists (select 1 from public.gimisco_admins a where a.user_id = (select auth.uid())));
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='gimisco_admins' and policyname='Admins can read own authorization') then
    create policy "Admins can read own authorization" on public.gimisco_admins for select to authenticated using (user_id = (select auth.uid()));
  end if;
end $$;

-- Public bucket allows public URLs to display published media. It does not expose the admin dashboard.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('gimisco-media','gimisco-media',true,52428800,array['image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm','video/quicktime'])
on conflict (id) do update set public=true, file_size_limit=52428800,
  allowed_mime_types=array['image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm','video/quicktime'];

do $$ begin
  if not exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='GIMISCO media public read') then
    create policy "GIMISCO media public read" on storage.objects for select to public using (bucket_id='gimisco-media');
  end if;
  if not exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='GIMISCO admins upload media') then
    create policy "GIMISCO admins upload media" on storage.objects for insert to authenticated with check (bucket_id='gimisco-media' and exists (select 1 from public.gimisco_admins a where a.user_id=(select auth.uid())));
  end if;
  if not exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='GIMISCO admins update media objects') then
    create policy "GIMISCO admins update media objects" on storage.objects for update to authenticated using (bucket_id='gimisco-media' and exists (select 1 from public.gimisco_admins a where a.user_id=(select auth.uid()))) with check (bucket_id='gimisco-media' and exists (select 1 from public.gimisco_admins a where a.user_id=(select auth.uid())));
  end if;
  if not exists (select 1 from pg_policies where schemaname='storage' and tablename='objects' and policyname='GIMISCO admins delete media objects') then
    create policy "GIMISCO admins delete media objects" on storage.objects for delete to authenticated using (bucket_id='gimisco-media' and exists (select 1 from public.gimisco_admins a where a.user_id=(select auth.uid())));
  end if;
end $$;

